//! `aegist learn`: collect code to train on - from a folder, a git
//! repository, or a ready-made pack of well-known open-source projects.
//!
//! Files are filtered the way a careful person would: only source code,
//! nothing git ignores, no generated or minified files, no exact
//! duplicates. What's kept is copied to data/corpus/<source>/, and every
//! name used in it goes into data/names/<source>.txt - the list Aegist
//! checks its own code against, so it can tell when it has made a name up.

use crate::config::Settings;
use crate::corpus::{self, clean_code};
use crate::lang;
use crate::util::fnv1a;
use anyhow::{bail, Context, Result};
use std::collections::{BTreeSet, HashSet};
use std::path::{Path, PathBuf};
use std::process::Command;

#[derive(Debug, Default)]
pub struct Learned {
    pub source: String,
    pub files: usize,
    pub bytes: u64,
    pub skipped: usize,
    pub duplicates: usize,
    pub names: usize,
}

/// Folders that hold dependencies, builds or caches, never skipped by
/// accident even when a project forgot to git-ignore them.
const SKIP_DIRS: &[&str] = &[
    "node_modules", "vendor", "target", "dist", "build", "out", ".git", "__pycache__", ".venv", "venv", "env", ".tox", ".mypy_cache",
    ".pytest_cache", ".next", ".nuxt", "coverage", "bower_components", ".gradle", ".idea", ".vscode", "third_party", "site-packages",
];

/// Why a file isn't worth training on, if it isn't.
pub fn reject_reason(path: &Path, bytes: &[u8], settings: &Settings) -> Option<&'static str> {
    let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
    if !lang::is_code(path) {
        return Some("not source code");
    }
    if name.contains(".min.") || name.ends_with(".lock") || name.ends_with("-lock.json") || name == "package-lock.json" || name.ends_with(".map") {
        return Some("generated");
    }
    if bytes.len() as u64 > settings.code.max_file_kb * 1024 {
        return Some("too big");
    }
    if bytes.contains(&0) {
        return Some("binary");
    }
    if name.ends_with(".json") && bytes.len() > 64 * 1024 {
        return Some("data");
    }
    let text = String::from_utf8_lossy(bytes);
    if text.lines().any(|l| l.len() > settings.code.max_line_chars) {
        return Some("minified");
    }
    let head: String = text.chars().take(600).collect::<String>().to_lowercase();
    if head.contains("do not edit") || head.contains("autogenerated") || head.contains("auto-generated") || head.contains("@generated") {
        return Some("generated");
    }
    if text.trim().is_empty() {
        return Some("empty");
    }
    None
}

/// Every candidate source file under `root`, as git would see them.
pub fn source_files(root: &Path) -> Vec<PathBuf> {
    if root.is_file() {
        return vec![root.to_path_buf()];
    }
    let mut files: Vec<PathBuf> = ignore::WalkBuilder::new(root)
        .hidden(true)
        .git_ignore(true)
        .git_global(false)
        .require_git(false)
        .filter_entry(|e| !(e.file_type().is_some_and(|t| t.is_dir()) && SKIP_DIRS.contains(&e.file_name().to_str().unwrap_or(""))))
        .build()
        .flatten()
        .filter(|e| e.file_type().is_some_and(|t| t.is_file()))
        .map(|e| e.into_path())
        .filter(|p| lang::is_code(p))
        .collect();
    files.sort();
    files
}

/// A folder name that's safe on every system.
pub fn source_name(raw: &str) -> String {
    let base = raw.trim_end_matches(['/', '\\']).trim_end_matches(".git");
    let base = base.rsplit(['/', '\\', ':']).next().unwrap_or(base);
    let clean: String = base.chars().map(|c| if c.is_ascii_alphanumeric() || c == '-' || c == '_' || c == '.' { c } else { '-' }).collect();
    let clean = clean.trim_matches(['-', '.']).to_string();
    if clean.is_empty() { "code".into() } else { clean }
}

fn names_dir(settings: &Settings) -> PathBuf {
    settings.data_path("names")
}

/// Hashes of every file already in the corpus, to skip exact duplicates.
fn corpus_hashes(settings: &Settings, except: &Path) -> HashSet<u64> {
    corpus::corpus_files(settings)
        .into_iter()
        .filter(|f| !f.starts_with(except))
        .filter_map(|f| std::fs::read(f).ok())
        .map(|b| fnv1a(clean_code(&b).as_bytes()))
        .collect()
}

/// Copy the code in `root` (a folder or file) into the corpus as `source`,
/// replacing what an earlier `learn` of the same source put there.
pub fn learn_path(settings: &Settings, root: &Path, source: Option<&str>, log: &mut dyn FnMut(String)) -> Result<Learned> {
    if !root.exists() {
        bail!("{} doesn't exist", root.display());
    }
    let root = root.canonicalize()?;
    let source = source.map(source_name).unwrap_or_else(|| source_name(&root.to_string_lossy()));
    let dest = corpus::corpus_dir(settings).join(&source);
    let seen = corpus_hashes(settings, &dest);
    if dest.exists() {
        std::fs::remove_dir_all(&dest).with_context(|| format!("clearing {}", dest.display()))?;
    }
    let files = source_files(&root);
    log(format!("Reading {} source files in {}...", files.len(), root.display()));
    let mut report = Learned { source: source.clone(), ..Default::default() };
    let mut hashes: HashSet<u64> = HashSet::new();
    let mut names: BTreeSet<String> = BTreeSet::new();
    for f in &files {
        let Ok(bytes) = std::fs::read(f) else { continue };
        if reject_reason(f, &bytes, settings).is_some() {
            report.skipped += 1;
            continue;
        }
        let code = clean_code(&bytes);
        let h = fnv1a(code.as_bytes());
        if seen.contains(&h) || !hashes.insert(h) {
            report.duplicates += 1;
            continue;
        }
        let rel = if root.is_file() { PathBuf::from(f.file_name().unwrap_or_default()) } else { f.strip_prefix(&root).unwrap_or(f).to_path_buf() };
        let to = dest.join(&rel);
        if let Some(parent) = to.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&to, code.as_bytes())?;
        names.extend(lang::identifiers(&code).filter(|w| w.len() >= 2).map(str::to_string));
        report.files += 1;
        report.bytes += code.len() as u64;
    }
    report.names = names.len();
    let list: String = names.into_iter().map(|n| n + "\n").collect();
    std::fs::write(names_dir(settings).join(format!("{source}.txt")), list)?;
    Ok(report)
}

/// Clone a git repository (shallow) into data/sources/ and learn from it.
pub fn learn_git(settings: &Settings, url: &str, log: &mut dyn FnMut(String)) -> Result<Learned> {
    let name = source_name(url);
    let dir = settings.data_path("sources").join(&name);
    if dir.join(".git").is_dir() {
        log(format!("Updating {name}..."));
        let mut cmd = Command::new("git");
        cmd.arg("-C").arg(&dir).args(["pull", "--quiet", "--depth", "1"]);
        let ok = crate::proc::run(cmd, Some(std::time::Duration::from_secs(600)), None).is_ok_and(|o| o.ok());
        if !ok {
            log(format!("Couldn't update {name}; using the copy already downloaded."));
        }
    } else {
        log(format!("Downloading {url}..."));
        if dir.exists() {
            std::fs::remove_dir_all(&dir)?;
        }
        if crate::proc::which("git").is_none() {
            bail!("downloading needs git - install it from https://git-scm.com");
        }
        let mut cmd = Command::new("git");
        cmd.args(["clone", "--depth", "1", "--single-branch", "--quiet", url]).arg(&dir);
        let out = crate::proc::run(cmd, Some(std::time::Duration::from_secs(1800)), None).context("couldn't run git")?;
        if !out.ok() {
            let why = out.combined();
            bail!("git couldn't download {url}: {}", why.lines().last().unwrap_or("no reason given"));
        }
    }
    learn_path(settings, &dir, Some(&name), log)
}

/// A source argument: a git URL, or a folder/file.
pub fn is_git_url(s: &str) -> bool {
    s.starts_with("https://") || s.starts_with("http://") || s.starts_with("git@") || s.starts_with("ssh://") || s.ends_with(".git")
}

