/// What's in the corpus: (source, files, bytes), biggest first.
pub fn sources(settings: &Settings) -> Vec<(String, usize, u64)> {
    let root = corpus::corpus_dir(settings);
    let mut out: Vec<(String, usize, u64)> = Vec::new();
    for f in corpus::corpus_files(settings) {
        let rel = f.strip_prefix(&root).unwrap_or(&f).to_string_lossy().replace('\\', "/");
        let src = rel.split('/').next().unwrap_or("").to_string();
        let size = std::fs::metadata(&f).map(|m| m.len()).unwrap_or(0);
        match out.iter_mut().find(|s| s.0 == src) {
            Some(s) => {
                s.1 += 1;
                s.2 += size;
            }
            None => out.push((src, 1, size)),
        }
    }
    out.sort_by(|a, b| b.2.cmp(&a.2));
    out
}

/// Forget a source: its code and its names.
pub fn forget(settings: &Settings, source: &str) -> Result<bool> {
    let dir = corpus::corpus_dir(settings).join(source_name(source));
    let names = names_dir(settings).join(format!("{}.txt", source_name(source)));
    let existed = dir.exists();
    if existed {
        std::fs::remove_dir_all(&dir)?;
    }
    let _ = std::fs::remove_file(names);
    Ok(existed)
}

/// Every name that appears anywhere in the code Aegist learned from.
pub fn known_names(settings: &Settings) -> HashSet<String> {
    let mut all = HashSet::new();
    if let Ok(entries) = std::fs::read_dir(names_dir(settings)) {
        for e in entries.flatten() {
            if let Ok(text) = std::fs::read_to_string(e.path()) {
                all.extend(text.lines().map(str::to_string));
            }
        }
    }
    all
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::testing;

    #[test]
    fn learns_only_real_source_code_once() {
        let tmp = tempfile::tempdir().unwrap();
        let s = testing::settings(&tmp.path().join("data"));
        let src = tmp.path().join("My Project");
        for (path, text) in [
            ("main.py", "def greet(name):\n    return 'hi ' + name\n"),
            ("copy.py", "def greet(name):\n    return 'hi ' + name\n"),
            ("lib/util.rs", "pub fn twice(x: i32) -> i32 { x * 2 }\n"),
            ("notes.txt", "not code"),
            ("app.min.js", "var a=1;"),
            ("node_modules/dep/index.js", "module.exports = 1;\n"),
            ("gen.py", "# Code generated by a tool. DO NOT EDIT.\nx = 1\n"),
            ("ignored/skip.py", "x = 2\n"),
        ] {
            let p = src.join(path);
            std::fs::create_dir_all(p.parent().unwrap()).unwrap();
            std::fs::write(p, text).unwrap();
        }
        std::fs::write(src.join(".gitignore"), "ignored/\n").unwrap();
        let r = learn_path(&s, &src, None, &mut |_| {}).unwrap();
        assert_eq!(r.source, "My-Project");
        assert_eq!((r.files, r.duplicates), (2, 1), "{r:?}");
        let learned = sources(&s);
        assert_eq!(learned.len(), 1);
        assert_eq!(learned[0].1, 2);
        let names = known_names(&s);
        assert!(names.contains("greet") && names.contains("twice") && !names.contains("exports"));
        // learning again replaces, not duplicates
        assert_eq!(learn_path(&s, &src, None, &mut |_| {}).unwrap().files, 2);
        assert!(forget(&s, "My-Project").unwrap());
        assert!(sources(&s).is_empty() && known_names(&s).is_empty());
    }

    #[test]
    fn names_and_urls() {
        assert_eq!(source_name("https://github.com/psf/requests.git"), "requests");
        assert_eq!(source_name("/home/me/code/my app/"), "my-app");
        assert!(is_git_url("https://github.com/a/b") && is_git_url("git@github.com:a/b.git") && !is_git_url("./src"));
        assert!(pack("Python").is_some() && pack("cobol").is_none());
        assert!(PACKS.iter().all(|p| p.repos.iter().all(|r| r.starts_with("https://github.com/"))));
    }
}
